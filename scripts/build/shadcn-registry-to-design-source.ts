/**
 * The shadcn registry snapshot, turned into the typed design source the
 * default-design generator consumes ([internal ref] D1).
 *
 * `scripts/build/generate-default-design.ts` reads ONE typed object, today
 * `DEFAULT_DESIGN_SOURCE` in `src/admin/config/design.ts`, and derives the five
 * token files from it. [internal ref] replaces the hand-written values with shadcn's:
 * this module reads `[internal ref]` and returns an object
 * of the same `DefaultDesignSource` shape, so the generator's derivations keep
 * their shape when its input changes.
 *
 * ## What comes from the registry, and what does not
 *
 * | Field of the source | From |
 * |---|---|
 * | `v1.light`, `v1.dark` | `colors/neutral.json` `cssVarsV4`, every variable under shadcn's own name |
 * | `colorRegistrations` | one `--color-<name>: var(--<name>)` per colour variable (plan §6, "one name layer") |
 * | `roleBridge` | the remainder's extension roles, untouched (the `--sv-*` alias layer left in P10) |
 * | `scales.fontFamilies.sans` / `.mono` | `font-geist.json`, and `font-geist-mono` in the base-nova `registry.json` |
 * | `scales.radii` | the `--radius-*` ladder the pinned `shadcn` computes from `--radius` |
 * | everything else | `extensions`: the parts shadcn does not declare, passed through untouched |
 *
 * `extensions` is today's `DEFAULT_DESIGN_SOURCE`. What survives of it is the
 * P3 flip's decision, not this module's: plan §6.1 says the Sovrium roles
 * base-nova does not declare are not minted in the default.
 *
 * ## The one conversion: chart hues to `#rrggbb`
 *
 * Every value is emitted as the snapshot spells it, except `chart-1` …
 * `chart-5`. Two consumers need six-digit hex for those: `deriveOptionChipColors`
 * parses nothing else, and `Chart Palette Drift` compares byte for byte. The
 * conversion is `srgbHex` (`src/domain/kernel/color/color-contrast.ts`): Oklch →
 * Oklab → LMS → linear sRGB (Ottosson's matrices), the sRGB transfer function,
 * then rounding to 8 bits per channel, lower-cased to the spelling the chart
 * palette already uses. Precision is the 8-bit quantisation only: each channel
 * is within 0.5/255 of the exact gamma-encoded value. A hue outside the sRGB
 * gamut has no faithful hex, so it throws rather than clamping.
 *
 * Pure: file reads and data. Nothing here writes, and the generator does not
 * import it until the P3 flip, so landing it changes no generated byte.
 */

import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { srgbHex } from '@/domain/kernel/color/color-contrast'
import { SHADCN_REGISTRY_DIR } from './pull-shadcn-registry'
import { SOVRIUM_DESIGN_REMAINDER } from './sovrium-design-remainder'
import type {
  BlockItem,
  DefaultDesignSource,
  DesignRemainder,
  Scale,
  TokenBlock,
  TokenDecl,
  ValueSpec,
} from './design-source-types'

const REPO_ROOT = join(import.meta.dir, '..', '..')

/** The colour variables of one scheme, as `cssVarsV4` spells them. */
type CssVars = Readonly<Record<string, string>>

/** What the transformer reads out of the snapshot. */
export interface ShadcnRegistrySnapshot {
  /** The `shadcn` version the snapshot was pulled at. */
  readonly version: string
  /** `colors/neutral.json` `cssVarsV4.light`, `radius` included. */
  readonly light: CssVars
  /** `colors/neutral.json` `cssVarsV4.dark`. */
  readonly dark: CssVars
  /** `font-geist.json` `font.family`. */
  readonly sansFamily: string
  /** The base-nova `registry.json` item `font-geist-mono`'s `font.family`. */
  readonly monoFamily: string
}

/**
 * The `--radius-*` ladder, as shadcn 4.21.4 computes it from `--radius`. It is
 * code in the pinned CLI (`@shadcn/registry` 0.1.3, the dependency that writes a
 * theme's `@theme inline` block), not a registry item, so it cannot be read
 * from the snapshot; the test re-reads it out of the installed package so a
 * version bump that moves it fails here rather than shipping stale.
 */
export const SHADCN_RADIUS_LADDER = {
  sm: 'calc(var(--radius) * 0.6)',
  md: 'calc(var(--radius) * 0.8)',
  lg: 'var(--radius)',
  xl: 'calc(var(--radius) * 1.4)',
  '2xl': 'calc(var(--radius) * 1.8)',
  '3xl': 'calc(var(--radius) * 2.2)',
  '4xl': 'calc(var(--radius) * 2.6)',
} as const

/**
 * Each retired `--sv-*` role and the shadcn variable that replaced it, plan
 * §6.1's "today's `--sv-*` role" column. NOTHING is emitted from it: the
 * `--sv-<role>: var(--<shadcn>)` alias layer left in P10 (plan §6.5). It stays
 * as data because a Sovrium author key (`background-raised`) and a `TOKENS`
 * catalogue key (`bgRaised`) still name the role, and both now resolve to the
 * twin (`card`) through this table.
 */
export const RETIRED_SV_ROLE_TWINS: Readonly<Record<string, string>> = {
  bg: 'background',
  fg: 'foreground',
  'bg-raised': 'card',
  'bg-overlay': 'popover',
  primary: 'primary',
  'primary-fg': 'primary-foreground',
  'bg-subtle': 'muted',
  'fg-muted': 'muted-foreground',
  'error-solid': 'destructive',
  border: 'border',
  'focus-ring': 'ring',
  'chart-1': 'chart-1',
  'chart-2': 'chart-2',
  'chart-3': 'chart-3',
  'chart-4': 'chart-4',
  'chart-5': 'chart-5',
}

/** `chart-1` … `chart-5`: the variables emitted as hex rather than as spelled. */
const isChartVariable = (name: string): boolean => /^chart-\d+$/.test(name)

/** The `--radius` base: a dimension, not a colour, so it gets no `--color-*`. */
const RADIUS_VARIABLE = 'radius'

/** `oklch(...)` → `#rrggbb`, refusing any colour sRGB cannot hold. */
export const chartHex = (name: string, value: string): string => {
  const hex = srgbHex(value)
  if (hex === undefined) {
    throw new Error(
      `${name}: ${value} has no faithful #rrggbb (out of the sRGB gamut, or not a colour srgbHex reads)`
    )
  }
  return hex.toLowerCase()
}

const readJson = (root: string, file: string): unknown =>
  JSON.parse(readFileSync(join(root, SHADCN_REGISTRY_DIR, file), 'utf8'))

const asRecord = (value: unknown, where: string): Readonly<Record<string, unknown>> => {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw new Error(`${where} is not an object`)
  }
  return value as Readonly<Record<string, unknown>>
}

const asCssVars = (value: unknown, where: string): CssVars => {
  const record = asRecord(value, where)
  for (const [name, spelled] of Object.entries(record)) {
    if (typeof spelled !== 'string') throw new TypeError(`${where}.${name} is not a string`)
  }
  return record as CssVars
}

const fontFamily = (item: unknown, where: string): string => {
  const { family } = asRecord(asRecord(item, where)['font'], `${where}.font`)
  if (typeof family !== 'string') throw new TypeError(`${where}.font.family is not a string`)
  return family
}

/** Read the snapshot files the transformer needs; throws on any shape surprise. */
export const readShadcnRegistrySnapshot = (root: string = REPO_ROOT): ShadcnRegistrySnapshot => {
  const manifest = asRecord(readJson(root, 'manifest.json'), 'manifest.json')
  const neutral = asRecord(readJson(root, 'colors/neutral.json'), 'colors/neutral.json')
  const v4 = asRecord(neutral['cssVarsV4'], 'colors/neutral.json cssVarsV4')
  const registry = asRecord(readJson(root, 'registry.json'), 'registry.json')
  const { items } = registry
  if (!Array.isArray(items)) throw new TypeError('registry.json items is not an array')
  const mono = items.find(
    (item: unknown) => asRecord(item, 'registry.json item')['name'] === 'font-geist-mono'
  )
  if (mono === undefined) throw new Error('registry.json declares no font-geist-mono item')
  if (typeof manifest['shadcn'] !== 'string')
    throw new TypeError('manifest.json shadcn is not a string')

  return {
    version: manifest['shadcn'],
    light: asCssVars(v4['light'], 'cssVarsV4.light'),
    dark: asCssVars(v4['dark'], 'cssVarsV4.dark'),
    sansFamily: fontFamily(readJson(root, 'font-geist.json'), 'font-geist.json'),
    monoFamily: fontFamily(mono, 'registry.json font-geist-mono'),
  }
}

const decl = (property: string, value: ValueSpec): TokenDecl => ({ kind: 'decl', property, value })

const comment = (text: string): BlockItem => ({ kind: 'comment', text })

/** The literal the snapshot spells, chart hues converted to `#rrggbb`. */
const snapshotValue = (name: string, value: string): string =>
  isChartVariable(name) ? chartHex(`--${name}`, value) : value

/** One scheme's variables, every one under shadcn's own name. */
const schemeItems = (vars: CssVars, scheme: string, version: string): readonly BlockItem[] => [
  comment(
    `/* shadcn ${version}, base-nova neutral, ${scheme} — scripts/baselines/shadcn-registry */`
  ),
  ...Object.entries(vars).map(([name, value]) => decl(`--${name}`, snapshotValue(name, value))),
]

/** A block of the remainder with the snapshot's variables appended. */
const withScheme = (
  block: TokenBlock,
  vars: CssVars,
  scheme: string,
  version: string
): TokenBlock => ({
  selector: block.selector,
  items: [...block.items, { kind: 'blank' }, ...schemeItems(vars, scheme, version)],
})

/**
 * The radius ladder as the engine emits it: shadcn's steps, with the
 * snapshot's `--radius` as the `var()` fallback so a page rendered without the
 * token layer (`ECO_DESIGN_LAYER=off`, where `--radius` is never declared)
 * still rounds; plus the remainder's Sovrium-only steps, in ladder order.
 */
const radiusLadder = (radius: string, remainder: Scale): Scale => {
  const ladder = Object.fromEntries(
    Object.entries(SHADCN_RADIUS_LADDER).map(([step, value]) => [
      step,
      value.replace('var(--radius)', `var(--radius, ${radius})`),
    ])
  )
  const order = ['none', 'sm', 'base', 'md', 'lg', 'xl', '2xl', '3xl', '4xl', 'full']
  const merged: Record<string, string> = { ...remainder, ...ladder }
  return Object.fromEntries(
    [
      ...order.filter((key) => key in merged),
      ...Object.keys(merged).filter((k) => !order.includes(k)),
    ].map((key) => [key, merged[key] ?? ''])
  )
}

/** `'Geist Variable', sans-serif` → `['Geist Variable', 'sans-serif']`. */
const fontStack = (family: string): readonly string[] =>
  family.split(',').map((part) => part.trim().replace(/^'(.*)'$/, '$1'))

/** `card-foreground` → `cardForeground`; `chart-1` → `chart1`. */
const camel = (kebab: string): string =>
  kebab.replace(/-([a-z0-9])/g, (_match, next: string) => next.toUpperCase())

/** The utility a shadcn colour variable is safelisted under. */
const shadcnUtility = (name: string): string => {
  if (name.endsWith('foreground')) return `text-${name}`
  if (name === 'border' || name === 'input' || name === 'sidebar-border') return `border-${name}`
  if (name === 'ring' || name === 'sidebar-ring') return `ring-${name}`
  return `bg-${name}`
}

/**
 * `design.colors` key → shadcn variable. Every shadcn colour name maps to
 * itself; each Sovrium author key whose retired `--sv-*` role has a shadcn twin
 * maps to that twin (`background-raised` → `card`).
 */
const designColorVars = (
  colourNames: readonly string[],
  legacyAliases: Readonly<Record<string, string>>
): Readonly<Record<string, string>> => ({
  ...Object.fromEntries(
    Object.entries(legacyAliases).flatMap(([key, role]) => {
      const twin = RETIRED_SV_ROLE_TWINS[role]
      return twin === undefined ? [] : [[key, twin] as const]
    })
  ),
  ...Object.fromEntries(colourNames.map((name) => [name, name])),
})

/**
 * The remainder's `@theme` registrations, every name shadcn also declares
 * re-pointed at the shadcn variable, then the shadcn names the remainder does
 * not register.
 */
const registrations = (remainder: TokenBlock, colourNames: readonly string[]): TokenBlock => {
  const registered = new Set(
    remainder.items.flatMap((item) => (item.kind === 'decl' ? [item.property] : []))
  )
  return {
    selector: remainder.selector,
    items: [
      ...remainder.items.map((item): BlockItem => {
        if (item.kind !== 'decl') return item
        const name = item.property.replace(/^--color-/, '')
        return colourNames.includes(name) ? decl(item.property, { alias: name }) : item
      }),
      { kind: 'blank' },
      comment('/* shadcn colour variables, registered under their own names */'),
      ...colourNames
        .filter((name) => !registered.has(`--color-${name}`))
        .map((name) => decl(`--color-${name}`, { alias: name })),
    ],
  }
}

/**
 * The design source the snapshot describes, in `DefaultDesignSource`'s shape.
 *
 * @param snapshot - {@link readShadcnRegistrySnapshot}'s reading.
 * @param remainder - the Sovrium parts the snapshot does not declare
 *   (`sovrium-design-remainder.ts`); each is kept, and completed with the
 *   snapshot's variables where it carries colours.
 */
export const shadcnRegistryToDesignSource = (
  snapshot: ShadcnRegistrySnapshot,
  remainder: DesignRemainder
): DefaultDesignSource => {
  const colourNames = Object.keys(snapshot.light).filter((name) => name !== RADIUS_VARIABLE)
  const unknownTwin = Object.values(RETIRED_SV_ROLE_TWINS).find(
    (name) => !colourNames.includes(name)
  )
  if (unknownTwin !== undefined) {
    throw new Error(
      `RETIRED_SV_ROLE_TWINS names --${unknownTwin}, which the snapshot does not declare`
    )
  }
  const radius = snapshot.light[RADIUS_VARIABLE]
  if (radius === undefined) throw new Error('cssVarsV4.light declares no --radius')
  const fontFamilies = {
    sans: { family: snapshot.sansFamily },
    mono: { family: snapshot.monoFamily },
    ...remainder.scales.fontFamilies,
  }
  const catalogued = new Set(
    remainder.tokenCatalogue.flatMap((item) => (item.kind === 'token' ? [item.key] : []))
  )
  const safelisted = new Set(
    remainder.safelist.colorUtilities.flatMap((item) =>
      item.kind === 'utility' ? [item.name] : []
    )
  )
  const { version } = snapshot

  return {
    ...remainder,
    shadcnNames: Object.keys(snapshot.light),
    designColorVars: designColorVars(colourNames, remainder.legacyAliases),
    safelist: {
      ...remainder.safelist,
      colorUtilities: [
        ...remainder.safelist.colorUtilities,
        { kind: 'comment', text: '// shadcn/ui colour utilities' },
        ...colourNames
          .map(shadcnUtility)
          .filter((name) => !safelisted.has(name))
          .map((name) => ({ kind: 'utility', name }) as const),
      ],
    },
    tokenCatalogue: [
      ...remainder.tokenCatalogue,
      { kind: 'blank' },
      {
        kind: 'comment',
        text: `// ---------- shadcn/ui variables (base-nova, ${version}) ----------`,
      },
      ...Object.keys(snapshot.light)
        .map(camel)
        .filter((key) => !catalogued.has(key))
        .map((key) => ({ kind: 'token', key }) as const),
    ],
    colorRegistrations: registrations(remainder.colorRegistrations, colourNames),
    scales: {
      ...remainder.scales,
      fontFamilies,
      radii: radiusLadder(radius, remainder.scales.radii),
    },
    v1: {
      light: withScheme(remainder.v1.light, snapshot.light, 'light', version),
      dark: withScheme(remainder.v1.dark, snapshot.dark, 'dark', version),
    },
    neutralFloor: {
      ...remainder.neutralFloor,
      light: withScheme(remainder.neutralFloor.light, snapshot.light, 'light', version),
      dark: withScheme(remainder.neutralFloor.dark, snapshot.dark, 'dark', version),
      scales: {
        ...remainder.neutralFloor.scales,
        radii: radiusLadder(radius, remainder.neutralFloor.scales.radii),
      },
    },
    inherited: {
      ...remainder.inherited,
      fontStacks: {
        sans: fontStack(snapshot.sansFamily),
        mono: fontStack(snapshot.monoFamily),
      },
    },
  }
}

/** The default design source: the pinned snapshot, completed by the remainder. */
export const defaultDesignSource = (root: string = REPO_ROOT): DefaultDesignSource =>
  shadcnRegistryToDesignSource(readShadcnRegistrySnapshot(root), SOVRIUM_DESIGN_REMAINDER)
