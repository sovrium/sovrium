const renderTriggersAndActions = (): string => {
  const triggers = unionMembers(astOf(TriggerSchema)).map((node) => {
    const type = typeLiteralOf(node)
    if (type === undefined)
      throw new SkillReferenceError('a trigger branch declares no `type` literal')
    return `| \`${type}\` | ${cell(proseAnnotationOf(node, 'description'), `trigger ${type}`)} |`
  })
  const actions = unionMembers(astOf(ActionSchema)).map((node) => {
    const type = typeLiteralOf(node)
    if (type === undefined)
      throw new SkillReferenceError('an action branch declares no `type` literal')
    const operator = typeLiteralOf(node, 'operator')
    const name = operator === undefined ? type : `${type} / ${operator}`
    return `| \`${type}\` | ${operator === undefined ? '—' : `\`${operator}\``} | ${cell(proseAnnotationOf(node, 'description'), `action ${name}`)} |`
  })
  return renderReference({
    title: 'Sovrium automation triggers and actions',
    lead:
      `Every trigger an automation can start from (${triggers.length}) and every action a step ` +
      `can run (${actions.length}), in the words of the schema. An action is chosen by its ` +
      '`type` and, within a family, its `operator`.',
    body: [
      '## Triggers',
      '',
      `Read: \`sovrium docs ${docsAddress('automation-triggers')}\``,
      '',
      '| Type | When it fires |',
      '| --- | --- |',
      ...triggers,
      '',
      '## Actions',
      '',
      `Read: \`sovrium docs ${docsAddress('automation-actions')}\``,
      '',
      '| Type | Operator | What it does |',
      '| --- | --- | --- |',
      ...actions,
      '',
    ].join('\n'),
  })
}

