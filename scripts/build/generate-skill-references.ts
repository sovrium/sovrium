/** Every reference file, repo-relative path → content. */
export const renderSkillReferences = async (root: string): Promise<ReadonlyMap<string, string>> => {
  const indexSource = readFileSync(join(root, 'src', 'cli', 'index.ts'), 'utf8')
  const rendered = new Map<string, string>([
    ['src/skills/sovrium-app/references/cli-verbs.generated.md', renderCliVerbs(indexSource)],
    ['src/skills/sovrium-data-model/references/field-types.generated.md', await renderFieldTypes()],
    [
      'src/skills/sovrium-pages/references/component-catalogue.generated.md',
      renderComponentCatalogue(),
    ],
    [
      'src/skills/sovrium-automations/references/triggers-and-actions.generated.md',
      renderTriggersAndActions(),
    ],
    ['src/skills/sovrium-seo-geo/references/seo-options.generated.md', renderSeoOptions()],
    ['src/skills/sovrium-design/references/design-options.generated.md', renderDesignOptions()],
    ['src/skills/sovrium-security/references/auth-options.generated.md', renderAuthOptions()],
    ['src/skills/sovrium-agents/references/agent-options.generated.md', renderAgentOptions()],
  ])
  const declared = [...SKILL_REFERENCE_FILES].toSorted()
  const written = [...rendered.keys()].toSorted()
  if (declared.join('\n') !== written.join('\n')) {
    throw new SkillReferenceError(
      'the rendered files and SKILL_REFERENCE_FILES (scripts/lib/skill-references.ts) disagree'
    )
  }
  return rendered
}

if (import.meta.main) {
  const check = process.argv.includes('--check')
  const rendered = await renderSkillReferences(REPO_ROOT)
  const stale = [...rendered].filter(([path, text]) => {
    const target = join(REPO_ROOT, path)
    return !existsSync(target) || readFileSync(target, 'utf8') !== text
  })
  if (check) {
    if (stale.length > 0) {
      console.log(
        `${stale.length} skill reference(s) stale — run \`bun run build:skill-references\`: ` +
          stale.map(([path]) => path).join(', ')
      )
      process.exit(1)
    }
    console.log(`skill references current — ${rendered.size} file(s)`)
  } else {
    for (const [path, text] of rendered) writeFileSync(join(REPO_ROOT, path), text)
    const lines = [...rendered].map(([path, text]) => `${path} (${text.split('\n').length} lines)`)
    console.log(`skill references — ${rendered.size} file(s):\n  ${lines.join('\n  ')}`)
    if (UNADDRESSABLE_OPTIONS.length > 0) {
      console.log(
        `  ${UNADDRESSABLE_OPTIONS.length} option path(s) \`sovrium docs config\` cannot address, ` +
          `printed bare: ${[...new Set(UNADDRESSABLE_OPTIONS)].join(', ')}`
      )
    }
  }
}
