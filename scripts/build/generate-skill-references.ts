/** The manual article documenting each field category. */
const FIELD_CATEGORY_ARTICLES: Readonly<Record<string, string>> = {
  text: 'fields/text-fields',
  numeric: 'fields/number-fields',
  'date-time': 'fields/datetime-fields',
  selection: 'fields/selection-fields',
  relational: 'fields/relational-fields',
  media: 'fields/attachment-fields',
  user: 'fields/user-audit-fields',
  advanced: 'fields',
  ai: 'fields/ai-fields',
}

/** A struct's `type` literal. */
const typeLiteralOf = (node: SchemaNode | undefined, key = 'type'): string | undefined => {
  const signature = node?.propertySignatures?.find((property) => String(property.name) === key)
  const type = signature?.type as SchemaNode | undefined
  const literal = (type as { readonly literal?: unknown } | undefined)?.literal
  return typeof literal === 'string' ? literal : undefined
}

/** Every struct a union reaches, `Suspend` links expanded. */
const unionMembers = (node: SchemaNode | undefined): readonly SchemaNode[] => {
  if (node === undefined) return []
  if (node._tag === 'Union') return (node.types ?? []).flatMap(unionMembers)
  if (node._tag === 'Suspend') {
    const { thunk } = node as { readonly thunk?: () => SchemaNode }
    return thunk === undefined ? [] : unionMembers(thunk())
  }
  return [node]
}

const renderFieldTypes = async (): Promise<string> => {
  const sections = await Promise.all(
    FIELD_TYPE_CATEGORIES.map(async (category) => {
      const barrel = (await import(
        `@/domain/models/app/tables/fields/field-types/${category.category}`
      )) as Readonly<Record<string, unknown>>
      const described = new Map(
        Object.entries(barrel)
          .filter(([name]) => name.endsWith('FieldSchema'))
          .map(([, value]) => astOf(value))
          .flatMap((node) => {
            const literal = typeLiteralOf(node)
            return literal === undefined ? [] : [[literal, node] as const]
          })
      )
      const address = FIELD_CATEGORY_ARTICLES[category.category]
      if (address === undefined) {
        throw new SkillReferenceError(
          `no manual article mapped for field category ${category.category}`
        )
      }
      return [
        `## ${category.title}`,
        '',
        `Read: \`sovrium docs ${docsAddress(address)}\``,
        '',
        '| Type | What it stores |',
        '| --- | --- |',
        ...category.types.map(
          (type) =>
            `| \`${type}\` | ${cell(proseAnnotationOf(described.get(type), 'description'), `field type ${type}`)} |`
        ),
        '',
      ].join('\n')
    })
  )
  const total = FIELD_TYPE_CATEGORIES.reduce((sum, category) => sum + category.types.length, 0)
  return renderReference({
    title: 'Sovrium field types',
    lead:
      `Every field type a table column can declare (${total}), by category, in the words of ` +
      'the schema. The options each type takes are in the article named under its category, or ' +
      'one at a time with `sovrium docs config tables[].fields[]`.',
    body: sections.join('\n'),
  })
}

