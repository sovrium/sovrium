const GENERATOR = 'scripts/build/generate-skill-references.ts'

/** Past this many lines a reference opens with a table of contents (the skill-format rule). */
const TOC_THRESHOLD = 100

/** Thrown when a source cannot supply what a row needs. Never a blank cell. */
export class SkillReferenceError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'SkillReferenceError'
  }
}

/** One table cell: whitespace collapsed, pipes escaped. Refuses an empty one. */
const cell = (text: string | undefined, what: string): string => {
  const flat = (text ?? '').replaceAll(/\s+/g, ' ').trim()
  if (flat === '') throw new SkillReferenceError(`no description available for ${what}`)
  return escapeMarkdownTableCell(flat)
}

/** A GitHub-style anchor for a `## ` heading. */
const anchorOf = (heading: string): string =>
  heading
    .toLowerCase()
    .replaceAll(/[^a-z0-9 _-]/g, '')
    .trim()
    .replaceAll(' ', '-')

/**
 * The file around a body: the generator marker, a version-free provenance line, a title,
 * one lead paragraph, and a table of contents when the result is long.
 */
export const renderReference = (input: {
  readonly title: string
  readonly lead: string
  readonly body: string
}): string => {
  const headings = [...input.body.matchAll(/^## (.+)$/gm)].map((match) => match[1] ?? '')
  const head = [
    `<!-- generated by ${GENERATOR} — do not edit -->`,
    '',
    `# ${input.title}`,
    '',
    `> Generated from the Sovrium schema by ${GENERATOR} — do not edit. It carries no version on purpose: when it and the binary you run disagree, the binary is right.`,
    '',
    input.lead,
    '',
  ]
  const draft = [...head, input.body.trimEnd(), ''].join('\n')
  if (draft.split('\n').length <= TOC_THRESHOLD || headings.length === 0) return draft
  const toc = ['## Contents', '', ...headings.map((h) => `- [${h}](#${anchorOf(h)})`), '']
  return [...head, ...toc, input.body.trimEnd(), ''].join('\n')
}

/** Whether `sovrium docs <address>` names a real section or article of the manual. */
const docsAddressExists = (address: string): boolean => {
  const [sectionSlug, articleSlug] = address.split('/')
  const section = SECTIONS.find((candidate) => candidate.slug === sectionSlug)
  if (section === undefined) return false
  return articleSlug === undefined || section.articles.some((a) => a.slug === articleSlug)
}

/** An address the generator is about to print, proven to resolve first. */
const docsAddress = (address: string): string => {
  if (!docsAddressExists(address)) {
    throw new SkillReferenceError(
      `\`sovrium docs ${address}\` names no section or article of the manual`
    )
  }
  return address
}

