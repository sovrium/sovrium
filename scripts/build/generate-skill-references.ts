/**
 * The global help is a two-column layout whose second column starts at a
 * fixed offset. Read by COLUMN, not by a run of spaces: a long synopsis
 * (`sovrium mcp [--project <dir>]`) leaves exactly one space before its
 * purpose, and a whitespace split would glue the two together.
 */
const PURPOSE_COLUMN = 32

/** One row of the global help split at {@link PURPOSE_COLUMN}, or `undefined`. */
const splitHelpRow = (line: string): readonly [string, string] | undefined =>
  line.length > PURPOSE_COLUMN && line[PURPOSE_COLUMN - 1] === ' '
    ? [line.slice(0, PURPOSE_COLUMN).trim(), line.slice(PURPOSE_COLUMN).trim()]
    : undefined

/** `sovrium <verb> …` in the first column. */
const HELP_ROW = /^sovrium (\S+)/
/** `--help, -h` in the first column. */
const OPTION_ROW = /^--([a-z-]+)/

/** Every dispatched verb, its usage line and its one-line purpose. */
export const cliVerbRows = (
  indexSource: string
): readonly { readonly verb: string; readonly usage: string; readonly purpose: string }[] => {
  const { commands } = extractDispatchCommands(indexSource)
  const help = extractGlobalHelpLines(indexSource)
  const purposes = new Map<string, string[]>()
  const synopses = new Map<string, string[]>()
  for (const line of help) {
    const [first, purpose] = splitHelpRow(line) ?? []
    // The Examples block shares the layout; its second column is a `# comment`.
    if (first === undefined || purpose === undefined || purpose.startsWith('#')) continue
    const verb = HELP_ROW.exec(first)?.[1]
    const option = OPTION_ROW.exec(first)?.[1]
    if (verb !== undefined) {
      purposes.set(verb, [...(purposes.get(verb) ?? []), purpose])
      synopses.set(verb, [...(synopses.get(verb) ?? []), first])
    } else if (option !== undefined) {
      // `help` and `version` dispatch but appear only as the flags they alias.
      purposes.set(option, [purpose])
      synopses.set(option, [`sovrium ${option}`])
    }
  }
  return commands
    .filter((verb) => !verb.startsWith('-'))
    .map((verb) => {
      // The `Usage:` line and its continuation lines (`       sovrium x y`),
      // so a verb with several forms lists all of them.
      const helpLines = getCommandHelp(verb)?.split('\n') ?? []
      const forms = helpLines[0]?.startsWith('Usage:')
        ? [
            helpLines[0].replace(/^Usage:\s*/, ''),
            ...helpLines
              .slice(1)
              .filter((l, i, all) => all.slice(0, i + 1).every((x) => /^\s+sovrium /.test(x)))
              .map((l) => l.trim()),
          ]
        : (synopses.get(verb) ?? [])
      return {
        verb,
        usage: cell(forms.join('`<br>`'), `the usage of ${verb}`),
        purpose: cell((purposes.get(verb) ?? []).join('; '), `the purpose of ${verb}`),
      }
    })
}

const renderCliVerbs = (indexSource: string): string => {
  const rows = cliVerbRows(indexSource)
  return renderReference({
    title: 'Sovrium CLI verbs',
    lead:
      `Every verb the \`sovrium\` binary dispatches (${rows.length}), with its usage line and ` +
      'what it is for. `sovrium <verb> --help` prints the full options of one verb; ' +
      '`sovrium docs cli-api` is the manual section about them.',
    body: [
      '## Verbs',
      '',
      '| Verb | Usage | Purpose |',
      '| --- | --- | --- |',
      ...rows.map((row) => `| \`${row.verb}\` | \`${row.usage}\` | ${row.purpose} |`),
    ].join('\n'),
  })
}

