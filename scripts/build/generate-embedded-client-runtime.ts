/**
 * Codegen: embed the `sovrium client` runtime wrapper into the compiled binary as
 * a source-text string constant.
 *
 * `sovrium client` writes ONE TypeScript file into the user's project: the
 * `fetch`-based runtime plus the app's own types. The runtime is authored as a
 * real, type-checked, unit-tested module (`src/cli/commands/client/runtime.ts`),
 * and this generator inlines its SOURCE TEXT into
 * `src/infrastructure/assets/embedded-client-runtime.generated.ts` so the verb
 * can write it out identically in dev and in the binary, with no filesystem read
 * at runtime — the same shape, and the same reasons, as
 * `generate-embedded-config-types.ts` (not a `with { type: 'text' }` import).
 *
 * ZERO DEPENDENCIES IS ENFORCED HERE
 * ----------------------------------
 * The generated client promises it imports nothing and needs nothing installed.
 * A single `import` in the runtime would break that in every user's project and
 * nothing at type-check time here would notice (the import resolves fine inside
 * this repository). So the generator refuses a runtime carrying an `import`,
 * `require(...)`, dynamic `import(...)` or `export ... from` line, and the build
 * stops before the binary would ship it.
 *
 * Deterministic: no timestamp, no environment-dependent text, so `Generated
 * Assets Drift` can regenerate and byte-compare.
 *
 * Regenerate:
 *   bun run build:client-runtime
 * (run automatically by `build:binary`).
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { printStderr } from '@/infrastructure/logging/cli-output'

const PROJECT_ROOT = join(import.meta.dir, '..', '..')

export const CLIENT_RUNTIME_SOURCE_PATH = join(
  PROJECT_ROOT,
  'src',
  'cli',
  'commands',
  'client',
  'runtime.ts'
)
export const CLIENT_RUNTIME_OUT_FILE = join(
  PROJECT_ROOT,
  'src',
  'infrastructure',
  'assets',
  'embedded-client-runtime.generated.ts'
)

/** A line of the runtime that would give the generated client a dependency. */
export interface DependencyLine {
  readonly line: number
  readonly text: string
}

const isCommentLine = (trimmed: string): boolean =>
  trimmed.startsWith('//') || trimmed.startsWith('*') || trimmed.startsWith('/*')

const DEPENDENCY_PATTERNS: readonly RegExp[] = [
  // `import x from`, `import type { X } from`, `import './side-effect'`, `import * as`
  /^import[\s{*'"]/,
  // `export { x } from`, `export * from`, `export type { X } from`
  /^export\s+(?:type\s+)?(?:\*|\{[^}]*\})(?:\s+as\s+\w+)?\s*from\b/,
  // the closing line of a multi-line `export { … } from '…'`
  /^\}\s*from\s*['"]/,
  /\brequire\s*\(/,
  /\bimport\s*\(/,
]

/** Every code line of `source` that imports, requires or re-exports something. */
export const findDependencyLines = (source: string): readonly DependencyLine[] =>
  source
    .split('\n')
    .map((text, index) => ({ line: index + 1, text, trimmed: text.trim() }))
    .filter(({ trimmed }) => trimmed.length > 0 && !isCommentLine(trimmed))
    .filter(({ trimmed }) => DEPENDENCY_PATTERNS.some((pattern) => pattern.test(trimmed)))
    .map(({ line, text }) => ({ line, text }))

/** Escape a payload for safe interpolation-free embedding in a template literal. */
export const escapeForTemplateLiteral = (text: string): string =>
  text.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${')

const HEADER = `/**
 * Copyright (c) 2025-2026 ESSENTIAL SERVICES
 *
 * This source code is licensed under the Business Source License 1.1
 * found in the LICENSE.md file in the root directory of this source tree.
 */

// AUTO-GENERATED by scripts/build/generate-embedded-client-runtime.ts — DO NOT EDIT.
//
// The source text of src/cli/commands/client/runtime.ts, which \`sovrium client\`
// writes verbatim into the user's generated client. Inlined as a string constant
// so the verb works identically in dev and in the compiled binary.
//
// Regenerate:
//   bun run build:client-runtime
`

/** Render the generated module for a runtime `source`. Throws on a dependency line. */
export const renderClientRuntimeModule = (source: string): string => {
  const offending = findDependencyLines(source)
  if (offending.length > 0) {
    const first = offending[0]!
    throw new Error(
      `client/runtime.ts must import nothing (the generated client is zero-dependency): ` +
        `line ${first.line}: ${first.text.trim()}`
    )
  }
  return `${HEADER}
/** The \`sovrium client\` runtime wrapper's source, written into the generated client. */
export const CLIENT_RUNTIME_SOURCE: string = \`${escapeForTemplateLiteral(source)}\`
`
}

const main = (): void => {
  const source = readFileSync(CLIENT_RUNTIME_SOURCE_PATH, 'utf8')
  const contents = (() => {
    try {
      return renderClientRuntimeModule(source)
    } catch (error) {
      printStderr(error instanceof Error ? error.message : String(error))
      return process.exit(1)
    }
  })()
  mkdirSync(dirname(CLIENT_RUNTIME_OUT_FILE), { recursive: true })
  writeFileSync(CLIENT_RUNTIME_OUT_FILE, contents)
  console.log(`embedded-client-runtime.generated.ts — runtime ${source.length} B`)
}

if (import.meta.main) {
  main()
}
